"""Build TODO.md (one test scenario per Querki FAQ entry) from faq.json.

  python3 -I faq/build-todo.py            (run from si/)

Re-running keeps the status mark of each entry already in TODO.md, so marks
edited by hand ([x] [~] [-]) survive a refresh of faq.json.
"""
import json
import os
import re
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
faq = json.load(open(os.path.join(HERE, "faq.json")))
todo_path = os.path.join(HERE, "TODO.md")

# keep existing marks: "- [x] <a id="q-..."
marks = {}
if os.path.exists(todo_path):
    for m in re.finditer(r'^- \[(.)\] <a id="([^"]+)">', open(todo_path).read(), re.M):
        marks[m.group(2)] = m.group(1)

PRODUCT_ORDER = ["Core game", "All", "Branch & Claw", "Promo", "Jagged Earth", "Promo 2",
                 "Horizons of Spirit Island", "Feather & Flame", "Nature Incarnate"]

def tid(e):
    return "q-" + e["id"].lstrip(".")

def short(s, n=320):
    s = re.sub(r"\s+", " ", s or "").strip()
    return s if len(s) <= n else s[: n - 1].rsplit(" ", 1)[0] + " …"

def md(s):
    return s.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")

def prod_key(e):
    ps = [q for q in (e.get("products") or []) if q]
    return min((PRODUCT_ORDER.index(p) if p in PRODUCT_ORDER else 99) for p in ps) if ps else 98

by_cat = defaultdict(list)
for e in faq:
    by_cat[e.get("category") or "(no category)"].append(e)
cats = sorted(by_cat, key=lambda c: (-len(by_cat[c]), c))
status = Counter(marks.get(tid(e), " ") for e in faq)
prods = Counter(p for e in faq for p in ([q for q in (e.get("products") or []) if q] or ["(none)"]))

out = []
w = out.append
w("# Spirit Island FAQ → Turn test scenarios")
w("")
w(f"One unit-test scenario per entry of the official Spirit Island FAQ on Querki "
  f"({len(faq)} entries, fetched 2026-10-11 from "
  f"<https://querki.net/raw/darker/spirit-island-faq/Question>). "
  f"Entry data, with full answers, is in `faq.json`; this file is generated by `faq/build-todo.py`, "
  f"which keeps the status marks below when re-run.")
w("")
w("## Plan")
w("")
w("- **One scenario per entry**: `faq/tests/<id>.t`, where `<id>` is the anchor below "
  "(e.g. `q-blight-card-flip-order`). It sets up the situation the question describes and "
  "ends with `-- expect:` lines stating the answer as tuples that must (or `-- expect-not:` must not) appear.")
w("- **Misconceptions**: `misconceptions/<id>.json`, a wrong reading of the rules as find/replace edits "
  "to a rule file; the runner checks that each makes the scenarios in its `caught_by` fail. Design and "
  "conventions: `DESIGN.md`.")
w("- **Base files** are named in a header line, e.g. `-- uses: core.t ext-actions.t`; the scenario is "
  "concatenated after them, as `run.sh` does.")
w("- **Runner**: `faq/faq.test.ts`, run from `si/` as `node --import tsx faq/faq.test.ts`, runs every "
  "scenario and checks its expectations, so each entry is a regression test for the engine and for "
  "`core.t`. A tuple matches when its rendered atom (interval dropped) equals the line, at any time "
  "in the run. `FAQ=<id>` runs one; `FAQ_DIR=<dir>` runs another folder "
  "(e.g. copies pointed at a deliberately broken `core.t`, to check a scenario can fail).")
w("- Many entries need rules that aren't formalized yet (most cards, Adversaries, Scenarios, Aspects). "
  "Writing the scenario is also the prompt to add that rule, as a pure addition where possible; "
  "an entry that forces a base rewrite is a finding for the report.")
w("")
w("Status marks: `[ ]` todo · `[x]` scenario passes · `[~]` partial (some clause untested) · "
  "`[!]` scenario written, fails · `[-]` not a rules question, no test (say why).")
w("")
w(f"**Progress:** {status.get('x', 0)} pass · {status.get('~', 0)} partial · {status.get('!', 0)} failing · "
  f"{status.get('-', 0)} skipped · {status.get(' ', 0)} todo, of {len(faq)}.")
w("")
w("## By category")
w("")
w("| Category | Entries | Done |")
w("|---|---:|---:|")
for c in cats:
    done = sum(1 for e in by_cat[c] if marks.get(tid(e), " ") in "x-")
    anchor = re.sub(r"[^a-z0-9 -]", "", c.lower()).strip().replace(" ", "-")
    w(f"| [{md(c)}](#{anchor}) | {len(by_cat[c])} | {done} |")
w("")
w("By product (an entry can list several): " + " · ".join(f"{p} {n}" for p, n in prods.most_common()) + ".")
w("")
for c in cats:
    w(f"## {c}")
    w("")
    for e in sorted(by_cat[c], key=lambda e: (prod_key(e), e["question"].lower())):
        mark = marks.get(tid(e), " ")
        meta = " · ".join(x for x in [", ".join(e.get("products") or []), ", ".join((e.get("tags") or [])[:6])] if x)
        w(f'- [{mark}] <a id="{tid(e)}"></a>**{md(short(e["question"], 400))}** ([FAQ]({e["url"]}))')
        if meta:
            w(f"  <br><sub>{md(meta)}</sub>")
        if e.get("answer"):
            w(f"  > {md(short(e['answer']))}")
    w("")
open(todo_path, "w").write("\n".join(out))
print(f"{len(faq)} entries, {len(cats)} categories -> {todo_path}")
